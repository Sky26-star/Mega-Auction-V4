import React, { useState, useEffect, useMemo } from 'react';
import { V3MiniAuctionSession, V3Player } from '@/lib/v3-auction-types';
import { createClient } from '@/lib/supabase/client';
import {
  Sparkles,
  Trophy,
  Loader2,
  AlertCircle,
  Play,
  Layers,
  ArrowRight,
  ShieldAlert
} from 'lucide-react';

interface MiniPoolReviewProps {
  auctionId: string;
  roomId: string;
  miniSession: V3MiniAuctionSession;
  isHost: boolean;
  onStartSuccess?: () => void;
}

interface MiniReviewLot {
  id: string;
  lot_index: number;
  base_price: number;
  status: string;
  player: V3Player;
}

export function MiniPoolReview({
  auctionId,
  roomId,
  miniSession,
  isHost,
  onStartSuccess
}: MiniPoolReviewProps) {
  const [lots, setLots] = useState<MiniReviewLot[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [duplicateWarning, setDuplicateWarning] = useState<string | null>(null);

  // Host start mini auction state
  const [isStarting, setIsStarting] = useState(false);
  const [startError, setStartError] = useState<string | null>(null);

  // Fetch canonical Mini lots generated by v3_close_mini_selection
  useEffect(() => {
    let isCancelled = false;
    async function loadMiniLots() {
      if (!auctionId) return;
      setLoading(true);
      setError(null);
      setDuplicateWarning(null);

      try {
        const supabase = createClient();
        const { data, error: lotsError } = await supabase
          .from('auction_lots')
          .select(`
            id,
            lot_index,
            base_price,
            status,
            is_mini_round,
            player:players(*)
          `)
          .eq('auction_id', auctionId)
          .eq('is_mini_round', true)
          .order('lot_index', { ascending: true });

        if (lotsError) throw lotsError;

        if (!isCancelled) {
          const rawLots = (data || []) as any[];
          const seenPlayerIds = new Set<string>();
          let hasDuplicate = false;

          const parsedLots: MiniReviewLot[] = rawLots.map(item => {
            const playerObj = Array.isArray(item.player) ? item.player[0] : item.player;
            if (playerObj?.id) {
              if (seenPlayerIds.has(playerObj.id)) {
                hasDuplicate = true;
              }
              seenPlayerIds.add(playerObj.id);
            }
            return {
              id: item.id,
              lot_index: item.lot_index,
              base_price: item.base_price,
              status: item.status,
              player: playerObj,
            };
          });

          if (hasDuplicate) {
            setDuplicateWarning('Warning: Potential duplicate candidate detected in lot sequence.');
          }

          setLots(parsedLots);
        }
      } catch (err: any) {
        console.error('Error loading mini auction lots for pool review:', err);
        if (!isCancelled) {
          setError(err.message || 'Failed to load Mini Auction lots');
        }
      } finally {
        if (!isCancelled) {
          setLoading(false);
        }
      }
    }

    loadMiniLots();
    return () => {
      isCancelled = true;
    };
  }, [auctionId]);

  // Host Action: Start Mini Auction
  const handleStartMiniAuction = async () => {
    if (!isHost || isStarting) return;
    setIsStarting(true);
    setStartError(null);

    try {
      const supabase = createClient();
      const { data, error } = await supabase.rpc('v3_start_mini_auction', {
        p_auction_id: auctionId
      });

      if (error) throw error;
      if (data && !data.success) {
        throw new Error(data.error || 'Failed to start Mini Auction');
      }

      onStartSuccess?.();
    } catch (err: any) {
      console.error('Start Mini Auction error:', err);
      setStartError(err.message || 'Failed to start Mini Auction');
      setIsStarting(false);
    }
  };

  // Role summary calculation
  const roleBreakdown = useMemo(() => {
    const counts: Record<string, number> = {};
    lots.forEach(lot => {
      const role = lot.player?.role || 'OTHER';
      counts[role] = (counts[role] || 0) + 1;
    });
    return counts;
  }, [lots]);

  if (loading) {
    return (
      <div className="w-full bg-[#141917] border border-[#2A312D] rounded-3xl p-16 flex flex-col items-center justify-center space-y-4 shadow-xl">
        <Loader2 className="w-10 h-10 animate-spin text-[#C9A227]" />
        <p className="font-mono text-xs text-[#9CA6A0] uppercase tracking-widest">
          FINALIZING MINI CANDIDATE POOL...
        </p>
      </div>
    );
  }

  if (error) {
    return (
      <div className="w-full bg-[#141917] border border-red-500/40 rounded-3xl p-8 flex flex-col items-center justify-center space-y-4 text-center">
        <AlertCircle className="w-10 h-10 text-red-400" />
        <h3 className="text-xl font-bold font-display uppercase tracking-tight text-[#F3F4F1]">
          Pool Review Error
        </h3>
        <p className="text-xs font-mono text-red-300 max-w-md">{error}</p>
      </div>
    );
  }

  return (
    <div className="w-full flex flex-col space-y-6">

      {/* Header Banner */}
      <div className="bg-[#141917] border border-[#2A312D] rounded-3xl p-6 sm:p-8 shadow-xl flex flex-col lg:flex-row items-start lg:items-center justify-between gap-6">
        <div>
          <div className="flex items-center space-x-2 mb-1">
            <span className="w-2.5 h-2.5 rounded-full bg-[#C9A227] animate-pulse" />
            <span className="font-mono text-xs font-bold text-[#C9A227] uppercase tracking-widest">
              PHASE: POOL REVIEW
            </span>
          </div>
          <h2 className="text-2xl sm:text-3xl font-black font-display uppercase tracking-tight text-[#F3F4F1]">
            MINI AUCTION CANDIDATE POOL
          </h2>
          <p className="text-xs font-mono text-[#9CA6A0] max-w-xl">
            Nominations are closed. Review the {lots.length} finalized {lots.length === 1 ? 'lot' : 'lots'} in authoritative auction order. Base prices reflect the 20% Mini Auction discount.
          </p>
        </div>

        {/* Start Action / Waiting Status */}
        <div className="shrink-0 w-full lg:w-auto">
          {isHost ? (
            <div className="flex flex-col items-start lg:items-end space-y-2">
              <button
                type="button"
                disabled={isStarting || lots.length === 0}
                onClick={handleStartMiniAuction}
                className="w-full sm:w-auto px-8 py-3.5 rounded-2xl bg-[#C9A227] hover:bg-[#B38D1C] text-[#0B0F0D] font-mono font-bold text-xs uppercase tracking-wider flex items-center justify-center space-x-2 shadow-xl transition-all hover:scale-105 active:scale-95 disabled:opacity-50 disabled:cursor-not-allowed cursor-pointer"
              >
                {isStarting ? (
                  <>
                    <Loader2 className="w-4 h-4 animate-spin" />
                    <span>STARTING MINI AUCTION...</span>
                  </>
                ) : (
                  <>
                    <Play className="w-4 h-4 fill-current" />
                    <span>START MINI AUCTION ({lots.length} LOTS)</span>
                  </>
                )}
              </button>
              {startError && (
                <p className="text-xs font-mono text-red-400">{startError}</p>
              )}
            </div>
          ) : (
            <div className="px-5 py-3 rounded-2xl bg-[#0B0F0D] border border-[#2A312D] flex items-center space-x-3 text-xs font-mono text-[#9CA6A0]">
              <Loader2 className="w-4 h-4 animate-spin text-[#C9A227]" />
              <span>WAITING FOR HOST TO START MINI AUCTION</span>
            </div>
          )}
        </div>
      </div>

      {/* Duplicate Warning */}
      {duplicateWarning && (
        <div className="p-3 rounded-xl bg-amber-950/40 border border-amber-500/40 text-amber-300 text-xs font-mono flex items-center space-x-2">
          <ShieldAlert className="w-4 h-4 shrink-0 text-amber-400" />
          <span>{duplicateWarning}</span>
        </div>
      )}

      {/* Summary Metrics Bar */}
      <div className="bg-[#141917]/70 border border-[#2A312D] rounded-2xl p-4 flex flex-wrap items-center justify-between gap-4">
        <div className="flex items-center space-x-4">
          <div className="flex items-center space-x-2 font-mono text-xs">
            <span className="text-[#9CA6A0] uppercase">Total Lots:</span>
            <span className="font-bold text-[#F3F4F1] font-mono-numbers px-2 py-0.5 rounded bg-[#0B0F0D] border border-[#2A312D]">
              {lots.length}
            </span>
          </div>

          {/* Role pills */}
          <div className="hidden sm:flex items-center space-x-2 font-mono text-xs">
            {Object.entries(roleBreakdown).map(([role, count]) => (
              <span
                key={role}
                className="px-2 py-0.5 rounded bg-[#0B0F0D] border border-[#2A312D] text-[#9CA6A0] text-[10px]"
              >
                {role}: <strong className="text-[#F3F4F1]">{count}</strong>
              </span>
            ))}
          </div>
        </div>

        <span className="font-mono text-xs text-[#9CA6A0]">
          Ordered by: <strong className="text-[#C9A227]">Lot Index ASC</strong>
        </span>
      </div>

      {/* Ordered Candidate Lots Grid */}
      {lots.length === 0 ? (
        <div className="w-full py-16 border-2 border-dashed border-[#2A312D] rounded-3xl bg-[#141917]/30 flex flex-col items-center justify-center space-y-2 text-center p-6">
          <p className="font-mono text-sm text-[#F3F4F1] font-bold uppercase tracking-wider">
            No Candidates Nominated
          </p>
          <p className="font-mono text-xs text-[#9CA6A0]">
            The selection window closed with zero nominations.
          </p>
        </div>
      ) : (
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4 gap-4">
          {lots.map((lot, idx) => {
            const player = lot.player;
            return (
              <div
                key={lot.id}
                className="relative rounded-2xl border border-[#2A312D] bg-[#141917] p-4 shadow-xl flex flex-col justify-between space-y-3 hover:border-[#C9A227]/40 transition-all"
              >
                {/* Header: Lot Order Index and Base Price */}
                <div>
                  <div className="flex justify-between items-start gap-2 mb-1.5">
                    <span className="font-mono font-black text-xs text-[#0B0F0D] bg-[#C9A227] px-2 py-0.5 rounded uppercase tracking-wider">
                      LOT #{idx + 1}
                    </span>
                    <div className="text-right">
                      <span className="font-mono-numbers font-black text-xs text-[#F3F4F1] block leading-none">
                        ₹{lot.base_price}L
                      </span>
                      <span className="text-[9px] font-mono text-emerald-400 block mt-0.5">
                        20% Discounted
                      </span>
                    </div>
                  </div>

                  <h4 className="font-black font-display uppercase tracking-tight text-[#F3F4F1] text-lg leading-tight mt-1">
                    {player?.name || 'Unknown Candidate'}
                  </h4>
                  <p className="text-[11px] font-mono font-bold text-[#9CA6A0] uppercase tracking-wider">
                    {player?.role || 'N/A'} • {player?.country || 'N/A'}
                  </p>
                </div>

                {/* Bottom Meta */}
                <div className="pt-2 border-t border-[#2A312D] flex items-center justify-between text-[10px] font-mono text-[#9CA6A0]">
                  <span>Set: {player?.category || 'CORE'}</span>
                  <span className="px-2 py-0.5 rounded bg-[#0B0F0D] border border-[#2A312D] text-[#C9A227] font-bold">
                    PENDING
                  </span>
                </div>
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
}
